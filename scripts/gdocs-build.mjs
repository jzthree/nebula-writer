#!/usr/bin/env node
// Build the Apps Script side of the Google Docs add-in:
//   gdocs/script/Code.js      — src/gdocs/script/main.ts bundled (IIFE) plus a
//                               global stub per exported function, which is
//                               what google.script.run and the add-on menu call
//   gdocs/script/Sidebar.html — the sidebar page, with the pane URL baked in
//
//   node scripts/gdocs-build.mjs            (part of `npm run build`)
//   WRITER_TLS_PORT=8443 node scripts/gdocs-build.mjs
import { build } from "esbuild";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const port = process.env.WRITER_TLS_PORT?.trim() || "8443";
const paneOrigin = `https://localhost:${port}`;
const paneUrl = `${paneOrigin}/gdocs/pane.html`;

const EXPORTED = [
  "onOpen",
  "onInstall",
  "nebulaShowSidebar",
  "nebulaReadDocument",
  "nebulaReadFocus",
  "nebulaFocusKey",
  "nebulaFingerprint",
  "nebulaSelect",
  "nebulaApply",
  "nebulaReadImage",
  "nebulaReplaceImage",
  "nebulaSelectImage",
  "nebulaInsertImage",
  "nebulaDeleteImage",
  "nebulaApplyTable",
  "nebulaSelectTable"
];

const result = await build({
  entryPoints: [resolve(root, "src/gdocs/script/main.ts")],
  bundle: true,
  format: "iife",
  globalName: "NebulaDocs",
  target: "es2020",
  platform: "neutral",
  write: false,
  legalComments: "none",
  logLevel: "warning"
});
const bundle = result.outputFiles[0].text;
const stubs = EXPORTED.map((name) => `function ${name}() { return NebulaDocs.${name}.apply(null, arguments); }`).join("\n");
const header = "// Generated by scripts/gdocs-build.mjs from src/gdocs/script/main.ts — do not edit.\n";
writeFileSync(resolve(root, "gdocs/script/Code.js"), `${header}${bundle}\n${stubs}\n`);

const template = readFileSync(resolve(root, "gdocs/script/Sidebar.template.html"), "utf8");
const allowed = JSON.stringify(EXPORTED.filter((name) => name.startsWith("nebula") && name !== "nebulaShowSidebar"));
writeFileSync(
  resolve(root, "gdocs/script/Sidebar.html"),
  template.replace(/__PANE_URL__/g, paneUrl).replace(/__PANE_ORIGIN__/g, paneOrigin).replace(/__ALLOWED_FUNCTIONS__/g, allowed)
);
console.log(`gdocs: wrote gdocs/script/Code.js (${(bundle.length / 1024).toFixed(0)} KB) and Sidebar.html (pane ${paneUrl})`);
